namespace Clabber.Backend.Domain.Enums
{
    public enum CampaignType
    {
        // Default/Unknown
        None = 0,

        // Direct promotion of a specific piece of media
        MediaPromotion = 1,

        // A call for creators to collaborate on a project
        Collaboration = 2,

        // Brand awareness or profile growth
        BrandAwareness = 3,

        // Influencer-style sponsorship or product shoutout
        Sponsorship = 4,

        // A giveaway or contest to drive engagement
        Contest = 5,

        // Purely educational or informational content
        Educational = 6
    }
}
